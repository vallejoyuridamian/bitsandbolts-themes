import { parseFragment, serialize } from 'parse5';
import { svgPathBbox } from 'svg-path-bbox';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { semanticContentIconCatalog, semanticIconAssetPath } from '../components/semantic-icons.js';

// Generation only. Provider paths remain authoritative; no browser geometry work.
export function contentIconGeometry(source) {
  const document = parseFragment(source);
  const svg = document.childNodes.find(node => node.tagName === 'svg');
  if (!svg) throw new TypeError('Content icon requires an SVG root.');
  const attrs = node => Object.fromEntries(node.attrs.map(({ name, value }) => [name, value]));
  const root = attrs(svg);
  const allowedRoot = new Set(['xmlns', 'viewBox', 'width', 'height']);
  if (Object.keys(root).some(key => !allowedRoot.has(key))) throw new TypeError('Unsupported content SVG root attributes.');
  const viewBox = (root.viewBox || '').trim().split(/[\s,]+/).map(Number);
  if (viewBox.length !== 4 || !viewBox.every(Number.isFinite) || viewBox[2] <= 0 || viewBox[3] <= 0) {
    throw new TypeError('Content icon requires a valid viewBox.');
  }
  const boxes = [];
  const allowedPath = new Set(['d', 'fill', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin', 'fill-rule', 'clip-rule']);
  for (const node of svg.childNodes) {
    if (node.nodeName === '#text' && !node.value.trim()) continue;
    if (node.tagName !== 'path') throw new TypeError(`Unsupported content SVG geometry: ${node.nodeName}`);
    const path = attrs(node);
    if (Object.keys(path).some(key => !allowedPath.has(key)) || !path.d) throw new TypeError('Unsupported content SVG path attributes.');
    let radius = 0;
    if (path.stroke && path.stroke !== 'none') {
      if (path['stroke-linecap'] !== 'round' || path['stroke-linejoin'] !== 'round') {
        throw new TypeError('Content stroke bounds require admitted round caps and joins.');
      }
      radius = Number(path['stroke-width']) / 2;
      if (!Number.isFinite(radius) || radius <= 0) throw new TypeError('Invalid content stroke width.');
    }
    if (path.fill === 'none' && !radius) continue;
    const [left, top, right, bottom] = svgPathBbox(path.d);
    boxes.push([left - radius, top - radius, right + radius, bottom + radius]);
  }
  if (!boxes.length) throw new TypeError('Content icon has no painted paths.');
  // Image SVGs clip at their viewport. Some provider paths intentionally extend
  // beyond it; a tighter variant must never reveal previously clipped artwork.
  const x = Math.max(viewBox[0], Math.min(...boxes.map(box => box[0])));
  const y = Math.max(viewBox[1], Math.min(...boxes.map(box => box[1])));
  const width = Math.min(viewBox[0] + viewBox[2], Math.max(...boxes.map(box => box[2]))) - x;
  const height = Math.min(viewBox[1] + viewBox[3], Math.max(...boxes.map(box => box[3]))) - y;
  if (![x, y, width, height].every(Number.isFinite) || width <= 0 || height <= 0) throw new TypeError('Invalid painted icon bounds.');
  // Intrinsic dimensions must agree with the new viewBox, including provider width/height.
  svg.attrs = svg.attrs.filter(attr => !['viewBox', 'width', 'height'].includes(attr.name));
  svg.attrs.push(...Object.entries({ viewBox: `${x} ${y} ${width} ${height}`, width: String(width), height: String(height) })
    .map(([name, value]) => ({ name, value })));
  return { canvas: viewBox, bounds: { x, y, width, height }, svg: `${serialize(document)}\n` };
}

export function generateContentIcons(root = '.') {
  const metadata = {};
  for (const family of ['font-awesome-solid', 'material-symbols-outlined', 'material-symbols-filled']) {
    for (const item of semanticContentIconCatalog({ family })) {
      const originalPath = semanticIconAssetPath(item.iconRole, { family: item.iconFamily });
      if (metadata[originalPath]) continue;
      const source = readFileSync(join(root, 'dist/web', originalPath), 'utf8');
      const { canvas, bounds, svg } = contentIconGeometry(source);
      const path = originalPath.replace('icons/', 'icons/content/');
      mkdirSync(dirname(join(root, 'dist/web', path)), { recursive: true });
      writeFileSync(join(root, 'dist/web', path), svg);
      metadata[originalPath] = { path, canvas, bounds };
    }
  }
  const output = `// Generated by scripts/content-icon-geometry.mjs from canonical provider SVGs.\nexport const semanticIconContentData = Object.freeze(${JSON.stringify(metadata, null, 2)});\n`;
  writeFileSync(join(root, 'components/semantic-icon-content-data.js'), output);
  writeFileSync(join(root, 'dist/web/components/semantic-icon-content-data.js'), output);
  return metadata;
}
